const char *deskpet_tr(deskpet_str_id_t id, deskpet_lang_t lang)
{
    if (id >= S_COUNT) return "?";
    return (lang == LANG_ZH) ? ZH[id] : EN[id];
}

void deskpet_set_lang(deskpet_lang_t lang)
{
    if (lang == LANG_EN || lang == LANG_ZH) s_lang = lang;
}

deskpet_lang_t deskpet_get_lang(void) { return s_lang; }
